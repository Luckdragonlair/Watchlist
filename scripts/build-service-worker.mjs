#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Keep this template in the fingerprint so changes to worker behavior get a new
// cache even when the app assets have not changed.
const runtime = `
const scope = new URL(self.registration.scope);
const cachePrefix = 'watchlist-v01-static:' + encodeURIComponent(scope.href) + ':';
const cacheName = cachePrefix + version;
const assetURLs = assets.map(path => new URL(path, scope).href);
const knownAssets = new Set(assetURLs);
const indexURL = new URL('index.html', scope).href;
const workerURL = new URL('service-worker.js', scope);

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(cacheName);
      await cache.addAll(assetURLs.map(url => new Request(url, { cache: 'reload' })));
    } catch (error) {
      await caches.delete(cacheName);
      throw error;
    }
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(cachePrefix) && name !== cacheName).map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') event.waitUntil(self.skipWaiting());
  if (event.data?.type === 'GET_VERSION') event.ports?.[0]?.postMessage({ version, cacheName, assets: assets.length });
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname) || url.pathname === workerURL.pathname) return;
  // Firebase Hosting owns these endpoints, including the auth iframe and
  // redirect handler. Returning the offline app here breaks sign-in.
  if (url.pathname.startsWith('/__/')) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(cacheName);
      return await cache.match(indexURL) || fetch(request);
    })());
    return;
  }
  if (!knownAssets.has(url.href)) return;
  event.respondWith((async () => {
    const cache = await caches.open(cacheName);
    return await cache.match(url.href) || fetch(request);
  })());
});
`;

async function scan(directory, relative = '') {
  const entries = await readdir(join(directory, relative), { withFileTypes: true });
  entries.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  const paths = [];
  for (const entry of entries) {
    const path = relative ? `${relative}/${entry.name}` : entry.name;
    if (path === 'service-worker.js') continue;
    if (entry.isSymbolicLink()) throw new Error(`Build contains a symbolic link: ${path}. Use regular build files.`);
    if (entry.isDirectory()) paths.push(...await scan(directory, path));
    else if (entry.isFile()) paths.push(path);
  }
  return paths;
}

export async function buildServiceWorker(directory = fileURLToPath(new URL('../dist/', import.meta.url))) {
  let paths;
  try { paths = await scan(directory); }
  catch (error) {
    if (error.code === 'ENOENT') throw new Error('The dist build folder is missing. Run the Vite build before generating the service worker.');
    throw error;
  }
  if (!paths.includes('index.html')) throw new Error('The dist build needs index.html before generating the service worker.');
  const fingerprint = createHash('sha256').update(runtime);
  for (const path of paths) {
    const bytes = await readFile(join(directory, path));
    fingerprint.update(JSON.stringify([path, bytes.byteLength, createHash('sha256').update(bytes).digest('hex')]));
  }
  const version = fingerprint.digest('hex');
  const assets = paths.map(path => path.split('/').map(encodeURIComponent).join('/'));
  const worker = `// Generated by scripts/build-service-worker.mjs.\nconst version = ${JSON.stringify(version)};\nconst assets = ${JSON.stringify(assets)};\n${runtime}`;
  await writeFile(join(directory, 'service-worker.js'), worker, 'utf8');
  return { version, assets: assets.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const result = await buildServiceWorker();
    console.log(`Service worker: ${result.assets} assets, version ${result.version.slice(0, 16)}.`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
